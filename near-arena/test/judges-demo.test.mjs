import assert from 'node:assert/strict';
import { test } from 'node:test';
import { readFileSync } from 'node:fs';
import { fixture } from './contract-session.test.mjs';

const enabled = Boolean(process.env.AFLOAT_JUDGES_WASM);
test('isolated judges voyage has no deadlines, preserves settlement and rejects stale advances', { skip: !enabled }, () => {
  const module = new WebAssembly.Module(readFileSync(process.env.AFLOAT_JUDGES_WASM));
  const { call, advance } = fixture(module, true);
  const a = 'player.testnet', b = 'guest.testnet';
  let c = call('open_judges_voyage');
  const id = c.id;
  const next = status => call('advance_judges_voyage', { campaign_id: id, expected_status: status }, a);
  assert.equal(c.funding_ends_at, 0);
  advance(1000 * 60 * 60 * 24 * 365);
  assert.equal(call('campaign').status, 'funding');
  assert.throws(() => next('funding'), /funding/);
  assert.throws(() => call('contribute', { amount: 6000, nonce: 1, campaign_id: id }, a), /unavailable/);
  call('contribute', { amount: 2000, nonce: 1, campaign_id: id }, a);
  assert.throws(() => next('funding'), /funding/);
  call('contribute', { amount: 1000, nonce: 1, campaign_id: id }, b);
  assert.equal(call('campaign').status, 'funding', 'full funding still waits for the judge');
  assert.equal(next('funding').status, 'sailing');
  assert.equal(next('funding').status, 'sailing', 'stale click must not skip sailing');
  advance(1000 * 60 * 60 * 24 * 365);
  assert.equal(call('campaign').status, 'sailing');
  assert.equal(next('sailing').status, 'auction');
  assert.throws(() => next('auction'), /bid/);
  call('bid', { amount: 7000, campaign_id: id }, a);
  call('bid', { amount: 8000, campaign_id: id }, b);
  assert.equal(call('account', { player: a }).balance, 8000, 'outbid amount fully refunded');
  advance(1000 * 60 * 60 * 24 * 365);
  assert.equal(call('campaign').status, 'auction');
  assert.equal(call('advance', { campaign_id: id }).status, 'auction', 'normal advance cannot bypass the manual gate');
  c = next('auction');
  assert.equal(c.status, 'settled');
  assert.equal(c.sale, 8000); assert.equal(c.fee, 400); assert.equal(c.net, 7600);
  assert.equal(call('account', { player: a }).payout, 5067);
  assert.equal(call('account', { player: b }).payout, 2533);
  const balances = [a, b].map(player => call('balance', { player }));
  next('auction');
  assert.deepEqual([a, b].map(player => call('balance', { player })), balances, 'replay cannot distribute twice');
  advance(1000 * 60 * 60 * 24 * 365);
  assert.equal(call('equip_voyage_award', { equipped: true }, b).award_equipped, true, 'no claim expiry');
  const newer = call('restart_judges_voyage', { campaign_id: id });
  assert.equal(newer.status, 'funding'); assert.equal(newer.id, id + 1);
  assert.equal(call('balance', { player: a }), 13067, 'profitable crew keeps its proceeds');
  assert.equal(call('balance', { player: b }), 10000, 'demo top-up is debited from the isolated reserve');
  assert.throws(() => next('funding'), /changed/);
  assert.equal(call('campaign_history')[0].status, 'settled');
});
